  if (m.includes("anh/em trai")) return "brother";
  if (m.includes("chị/em gái")) return "sister";
  if (m.includes("vợ")) return "wife";
  if (m.includes("chồng")) return "husband";
  if (m.includes("bố mẹ") || m.includes("cha mẹ")) return "parents";
