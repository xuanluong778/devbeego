export function topicImageBucket(topic) {
  const t = String(topic || "").toLowerCase();
  if (t.includes("động vật") || t.includes("animal")) return "animal";
  if (t.includes("trái cây") || t.includes("fruit") || t.includes("hoa quả")) return "fruit";
  if (t.includes("thức ăn") || t.includes("food") || t.includes("ăn")) return "food";
  if (t.includes("trường") || t.includes("school")) return "school";
  if (t.includes("gia đình") || t.includes("family") || t.includes("người")) return "family";
  if (t.includes("du lịch") || t.includes("travel")) return "travel";
  if (t.includes("công việc") || t.includes("job")) return "job";
  if (t.includes("cơ bản")) return "education";
  return "education";
}

export function lookupCuratedImage(row) {
  const word = String(row?.word || "")
    .toLowerCase()
    .trim()
    .replace(/\?$/, "");
  if (CURATED_VOCAB_IMAGES[word]) return CURATED_VOCAB_IMAGES[word];

  const firstToken = word.split(/\s+/)[0];
  if (firstToken && CURATED_VOCAB_IMAGES[firstToken]) return CURATED_VOCAB_IMAGES[firstToken];

  const fromMeaning = meaningImageKeyword(row?.vietnamese_meaning);
  if (fromMeaning && CURATED_VOCAB_IMAGES[fromMeaning]) return CURATED_VOCAB_IMAGES[fromMeaning];

  return "";
}

export function lookupTopicFallbackImage(row) {
  const bucket = topicImageBucket(row?.topic);
  return CURATED_VOCAB_IMAGES[bucket] || "";
}
